def render(mode, stats):
    p = PALETTES[mode]
    out = [
        '<svg xmlns="http://www.w3.org/2000/svg" width="900" height="500" viewBox="0 0 900 500" '
        f'font-family="Consolas, Menlo, monospace">',
        f'<rect x="0.5" y="0.5" width="899" height="499" rx="10" fill="{p["bg"]}" stroke="{p["border"]}"/>',
    ]
    for i, line in enumerate(ART.strip("\n").split("\n")):
        line_html = html.escape(line)
        out.append(f'<text x="25" y="{45 + i * 3.6}" fill="{p["art"]}" font-size="3px" xml:space="preserve">{line_html}</text>')
    for i, segs in enumerate(info_lines(stats)):
        if not segs:
            continue
        spans = "".join(f'<tspan fill="{p[c]}">{html.escape(t)}</tspan>' for t, c in segs)
        out.append(f'<text x="420" y="{45 + i * 21}" font-size="13px" xml:space="preserve">{spans}</text>')
    out.append("</svg>")
    return "\n".join(out)

